/**
 * build-demo.mjs — assemble dist-demo/, the static Vercel demo.
 *
 *   npm run ui:build:demo
 *
 * Three steps:
 *  1. The editor UI, built with VITE_ALE_DEMO=1 (demo mode baked
 *     in; lib/demoMode), output to dist-demo/ instead of the
 *     normal src/ui-dist. The normal `npm run ui:build` is not
 *     touched and does not set the flag.
 *  2. The sample project (projects/lumen) installed if needed.
 *  3. Lumen built standalone into dist-demo/preview/ — its own
 *     vite config minus the editor's consent-bridge plugin (the
 *     bridge belongs to a live ALE session), with base './' so
 *     the preview works from any path the demo is served at.
 *     The demo config is written into the lumen folder for the
 *     build and removed afterwards.
 *
 * The fixture the UI runs on (src/ui/demo/fixtureData.ts) is a
 * checked-in file, refreshed separately — see DEMO.md.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const distDemo = path.join(repoRoot, 'dist-demo')
const lumenRoot = path.join(repoRoot, 'projects', 'lumen')
const demoConfigPath = path.join(lumenRoot, 'vite.config.demo.mjs')

function run(cmd, args, opts = {}) {
  console.log(`\n$ ${cmd} ${args.join(' ')}`)
  execFileSync(cmd, args, { stdio: 'inherit', ...opts })
}

const LUMEN_DEMO_CONFIG = `import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

// Generated by scripts/build-demo.mjs for the demo build only:
// lumen's own vite.config.js adds the editor's consent-bridge
// plugin, which belongs to a live ALE session. The demo preview
// is a plain static build of the sample app.
export default defineConfig({
  plugins: [react()],
  base: './',
  build: { outDir: ${JSON.stringify(path.join(distDemo, 'preview'))}, emptyOutDir: true },
})
`

run('npx', ['vite', 'build', '--outDir', distDemo, '--emptyOutDir'], {
  cwd: repoRoot,
  env: { ...process.env, VITE_ALE_DEMO: '1' },
})

if (!fs.existsSync(path.join(lumenRoot, 'node_modules'))) {
  run('npm', ['install', '--prefix', 'projects/lumen'], { cwd: repoRoot })
}

fs.writeFileSync(demoConfigPath, LUMEN_DEMO_CONFIG)
try {
  run('npx', ['vite', 'build', '--config', 'vite.config.demo.mjs'], { cwd: lumenRoot })
} finally {
  fs.rmSync(demoConfigPath, { force: true })
}

const kb = (p) => (fs.statSync(p).size / 1024).toFixed(0)
console.log(`\ndist-demo ready: index.html ${kb(path.join(distDemo, 'index.html'))} KB, preview/index.html ${kb(path.join(distDemo, 'preview', 'index.html'))} KB`)
