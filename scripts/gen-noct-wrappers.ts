/**
 * Generate typed React wrappers for vendored noct-* custom elements.
 *
 *   npx tsx scripts/gen-noct-wrappers.ts <catalogTag...> --out <file.tsx>
 *
 * The wrappers are generated from catalog metadata (the same
 * NoctComponentMeta the components ship): declared props become
 * typed React props set as element *properties* (the reliable path
 * for Lit reactive properties in React 18), and emitted events
 * become on<Event> callback props wired with addEventListener.
 * Slots pass through as children — put slot="name" on the child.
 */
import fs from 'node:fs'
import { loadCatalog } from '../src/catalog/catalog.js'

const args = process.argv.slice(2)
const outIdx = args.indexOf('--out')
const out = outIdx >= 0 ? args[outIdx + 1] : null
const tags = args.filter((a, i) => a !== '--out' && i !== outIdx + 1)
if (!out || !tags.length) {
  console.error('usage: npx tsx scripts/gen-noct-wrappers.ts <tag...> --out <file.tsx>')
  process.exit(1)
}

const catalog = loadCatalog()
const pascal = (tag: string) => tag.replace(/(^|-)(\w)/g, (_m, _d, c: string) => c.toUpperCase())
const camelEvent = (evt: string) => 'on' + evt.replace(/(^|-)(\w)/g, (_m, _d, c: string) => c.toUpperCase())
const tsType = (t?: string) => (t === 'boolean' ? 'boolean' : t === 'number' ? 'number' : t === 'string' ? 'string' : 'unknown')

const lines: string[] = [
  '/**',
  ' * GENERATED by scripts/gen-noct-wrappers.ts from catalog/components.json.',
  ' * Do not edit by hand — regenerate when the catalog or vendored set changes.',
  ' * React wrappers for the vendored noct-* Lit elements: props are set as',
  ' * element properties, emitted events arrive as on<Event> callbacks, and',
  ' * slots are filled by putting slot="name" on child elements.',
  ' */',
  "import React, { forwardRef, useLayoutEffect, useRef } from 'react'",
  '',
  'type NoctBaseProps = {',
  '  className?: string',
  '  style?: React.CSSProperties',
  '  id?: string',
  '  slot?: string',
  '  children?: React.ReactNode',
  '}',
  '',
  'function createNoctComponent<Props extends object>(tag: string, propNames: string[], eventNames: string[]) {',
  '  type FullProps = Props & NoctBaseProps & Record<string, unknown>',
  '  const Comp = forwardRef<HTMLElement, FullProps>(function NoctComponent(props, outerRef) {',
  '    const innerRef = useRef<HTMLElement | null>(null)',
  '    const { children, className, style, id, slot, ...rest } = props as FullProps & Record<string, unknown>',
  '    useLayoutEffect(() => {',
  '      const el = innerRef.current as unknown as Record<string, unknown> | null',
  '      if (!el) return',
  '      for (const name of propNames) {',
  '        if (name in rest) el[name] = rest[name]',
  '      }',
  '    })',
  '    useLayoutEffect(() => {',
  '      const el = innerRef.current',
  '      if (!el) return',
  '      const attached: Array<[string, EventListener]> = []',
  '      for (const evt of eventNames) {',
  '        const handler = rest[`on${evt.replace(/(^|-)\\w/g, (s: string) => s.replace(\'-\', \'\').toUpperCase())}`] as EventListener | undefined',
  '        if (typeof handler === \'function\') {',
  '          el.addEventListener(evt, handler)',
  '          attached.push([evt, handler])',
  '        }',
  '      }',
  '      return () => { for (const [evt, h] of attached) el.removeEventListener(evt, h) }',
  '    })',
  '    return React.createElement(tag, {',
  '      ref: (node: HTMLElement | null) => {',
  '        innerRef.current = node',
  '        if (typeof outerRef === \'function\') outerRef(node)',
  '        else if (outerRef && typeof outerRef === \'object\') (outerRef as React.MutableRefObject<HTMLElement | null>).current = node',
  '      },',
  '      className, style, id, slot,',
  '    }, children)',
  '  })',
  '  Comp.displayName = tag',
  '  return Comp',
  '}',
  '',
]

for (const tag of tags) {
  const entry = catalog.components.find(c => c.tag === tag)
  if (!entry) {
    console.error(`no catalog entry for ${tag}`)
    process.exit(1)
  }
  const name = pascal(tag)
  lines.push(`export interface ${name}Props {`)
  for (const p of entry.props) {
    lines.push(`  ${p.name}?: ${tsType(p.type)}${p.description ? ` // ${p.description.replace(/\n/g, ' ')}` : ''}`)
  }
  for (const evt of entry.emits) {
    lines.push(`  ${camelEvent(evt)}?: (event: CustomEvent) => void`)
  }
  lines.push('}')
  lines.push(`export const ${name} = createNoctComponent<${name}Props>('${tag}', [${entry.props.map(p => `'${p.name}'`).join(', ')}], [${entry.emits.map(e => `'${e}'`).join(', ')}])`)
  lines.push('')
}

fs.writeFileSync(out, lines.join('\n'), 'utf-8')
console.log(`wrappers for ${tags.length} components -> ${out}`)
